private val AquaShapes = Shapes(
    extraSmall = RoundedCornerShape(8.dp),
    small = RoundedCornerShape(12.dp),
    medium = RoundedCornerShape(18.dp),
    large = RoundedCornerShape(26.dp),
    extraLarge = RoundedCornerShape(34.dp),
)

@Composable
fun AquaTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    content: @Composable () -> Unit,
) {
    MaterialTheme(
        colorScheme = if (darkTheme) AquaDarkColors else AquaLightColors,
        typography = AquaTypography,
        shapes = AquaShapes,
        content = content,
    )
}

/** Soft vertical aquatic gradient for hero surfaces / headers. */
fun aquaHeaderGradient(dark: Boolean): Brush = Brush.verticalGradient(
    if (dark) listOf(AquaDeep, Color(0xFF0B1A1E))
    else listOf(AquaPrimary, AquaCyan)
)

/** Diagonal turquoise gradient used by primary stat cards & charts. */
fun aquaCardGradient(): Brush = Brush.linearGradient(
    listOf(AquaPrimary, AquaTurquoise)
)
